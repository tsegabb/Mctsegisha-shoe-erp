import { Router } from 'express';
import { authRouter, usersRouter } from './auth.routes.ts';
import productsRouter, { brandsRouter, categoriesRouter } from './products.routes.ts';
import inventoryRouter from './inventory.routes.ts';
import { cashRouter, reportsRouter, salesRouter } from './sales.routes.ts';
import settingsRouter from './settings.routes.ts';
import { notFoundHandler } from '../middlewares/errorHandler.middleware.ts';

const api = Router();
api.use('/auth', authRouter);
api.use('/users', usersRouter);
api.use('/products', productsRouter);
api.use('/brands', brandsRouter);
api.use('/categories', categoriesRouter);
api.use('/sales', salesRouter);
api.use('/cash', cashRouter);
api.use(reportsRouter);
api.use(inventoryRouter);
api.use(settingsRouter);
api.use(notFoundHandler);
export default api;
